#!/usr/bin/env node
// Generate the same splitter cases from a second implementation, so the fixtures this library
// replays are not one project's opinion: LangChain's Python splitter and LangChain's JavaScript
// splitter are separate codebases, and the corpus below is the one in scripts/gen_split_vectors.py
// replayed through the JavaScript one.
//
// Only the configuration that implementation offers is covered here — the separator kept at the
// start, whitespace trimmed — because that is what its `keepSeparator: true` means. The other two
// placements are covered by the Python fixtures and by this library's own tests.
//
// The package is installed outside this repository, so no node_modules lands beside the sources:
//
//     mkdir -p /tmp/lcjs && cd /tmp/lcjs && npm install @langchain/textsplitters@0.1.0
//     NODE_PATH=/tmp/lcjs/node_modules node scripts/gen_langchainjs_cases.cjs \
//       > src/conformance/js_split_cases_wbtest.mbt
//
// Pinned on purpose: the splitter's defaults and its `keepSeparator` spelling changed between
// releases, and fixtures from another version would test a different algorithm.

const EXPECTED = "0.1.0";

const { RecursiveCharacterTextSplitter } = require("@langchain/textsplitters");

// The corpus of scripts/gen_split_vectors.py, in the same order. A case that drifts between the two
// scripts fails the conformance test that replays the fixtures, rather than passing quietly.
const CORPUS = [
  [
    "rag-overview",
    "Retrieval-augmented generation answers a question in two steps.\n\n" +
      "First, a retriever finds the passages that look relevant to the question. " +
      "Second, a model reads those passages and writes the answer.\n\n" +
      "The quality of the answer rarely depends on the model alone: it depends on what the " +
      "retriever was able to find.",
  ],
  [
    "code",
    "fn main {\n  let values = [1, 2, 3]\n  for value in values {\n    println(value)\n  }\n}",
  ],
  [
    "one-line",
    "the quick brown fox jumps over the lazy dog and keeps running past the fence into the field",
  ],
  ["no-separator", "unbreakablesupercalifragilisticexpialidociousandthensomemoreletters"],
  [
    "cjk",
    "检索增强生成分两步回答问题。\n\n第一步，检索器找出看起来相关的段落。第二步，模型读这些段落并写出答案。",
  ],
  ["padded", "\n\n  A first paragraph, indented.  \n\n\n\n  A second paragraph.  \n\n"],
  ["short", "one line"],
  ["long-word", "before supercalifragilisticexpialidocious after"],
];

const SEPARATORS = ["\n\n", "\n", " ", ""];

const CONFIGS = [
  [20, 5],
  [40, 10],
  [64, 0],
  [1000, 200],
];

function moonbitString(value) {
  let out = '"';
  for (const char of value) {
    const code = char.codePointAt(0);
    if (char === "\\") out += "\\\\";
    else if (char === '"') out += '\\"';
    else if (char === "\n") out += "\\n";
    else if (char === "\t") out += "\\t";
    else if (char === "\r") out += "\\r";
    else if (code >= 0x20 && code < 0x7f) out += char;
    else out += "\\u{" + code.toString(16).toUpperCase() + "}";
  }
  return out + '"';
}

async function main() {
  let installed = null;
  try {
    installed = require("@langchain/textsplitters/package.json").version;
  } catch {
    installed = null;
  }
  if (installed && installed !== EXPECTED) {
    process.stderr.write(
      `warning: generating from @langchain/textsplitters ${installed}, ` +
        `the fixtures were written for ${EXPECTED}\n`,
    );
  }
  const cases = [];
  for (const [name, text] of CORPUS) {
    for (const [chunkSize, chunkOverlap] of CONFIGS) {
      const splitter = new RecursiveCharacterTextSplitter({
        separators: SEPARATORS,
        chunkSize,
        chunkOverlap,
        keepSeparator: true,
      });
      cases.push({ name, text, chunkSize, chunkOverlap, expected: await splitter.splitText(text) });
    }
  }

  const lines = [
    "// Generated by scripts/gen_langchainjs_cases.cjs from @langchain/textsplitters",
    `// ${EXPECTED}. Do not edit: change the script and regenerate.`,
    "",
    "///|",
    "/// One splitter case from the JavaScript implementation: the text, the budget, what it produced.",
    "pub(all) struct JsSplitCase {",
    "  name : String",
    "  text : String",
    "  chunk_size : Int32",
    "  chunk_overlap : Int32",
    "  expected : Array[String]",
    "}",
    "",
    "///|",
    `/// The ${cases.length} cases the JavaScript implementation produced, replayed by the conformance test.`,
    "pub fn js_split_cases() -> Array[JsSplitCase] {",
    "  [",
  ];
  for (const item of cases) {
    const chunks = item.expected.map(moonbitString).join(", ");
    lines.push(
      "    { name: " +
        moonbitString(item.name) +
        ", text: " +
        moonbitString(item.text) +
        ", chunk_size: " +
        item.chunkSize +
        ", chunk_overlap: " +
        item.chunkOverlap +
        ", expected: [" +
        chunks +
        "] },",
    );
  }
  lines.push("  ]");
  lines.push("}");
  lines.push("");
  process.stdout.write(lines.join("\n"));
}

main();
