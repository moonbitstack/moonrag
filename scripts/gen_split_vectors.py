#!/usr/bin/env python3
"""Generate the splitter differential cases against langchain-text-splitters.

The library's recursive splitter must cut text exactly the way the reference implementation does.
This script runs the reference on a fixed corpus and writes the results as MoonBit source, so the
test suite replays them on every target without Python in the loop.

    python3 -m venv .venv && .venv/bin/pip install langchain-text-splitters==1.1.3
    .venv/bin/python scripts/gen_split_vectors.py > src/conformance/split_cases_wbtest.mbt

Pinned on purpose: the reference changed its default `keep_separator` to `"start"` and its default
`chunk_size` to 4000 between releases, and a fixture set generated by another version would test a
different algorithm. Re-running with a different version rewrites the file; commit the diff only when
the library is meant to follow the new behaviour.
"""

from __future__ import annotations

import sys

EXPECTED = "1.1.3"

CORPUS = [
    # Prose with paragraph, sentence and word boundaries at every level.
    (
        "rag-overview",
        "Retrieval-augmented generation answers a question in two steps.\n\n"
        "First, a retriever finds the passages that look relevant to the question. "
        "Second, a model reads those passages and writes the answer.\n\n"
        "The quality of the answer rarely depends on the model alone: it depends on what the "
        "retriever was able to find.",
    ),
    # Code: separators of every kind, no blank lines, deep indentation.
    (
        "code",
        "fn main {\n  let values = [1, 2, 3]\n  for value in values {\n    println(value)\n  }\n}",
    ),
    # One long line with nothing but spaces to split on.
    (
        "one-line",
        "the quick brown fox jumps over the lazy dog and keeps running past the fence into the field",
    ),
    # No separators at all: only the character splitter can cut this.
    (
        "no-separator",
        "unbreakablesupercalifragilisticexpialidociousandthensomemoreletters",
    ),
    # CJK: no spaces, so the character splitter does the work.
    (
        "cjk",
        "检索增强生成分两步回答问题。\n\n第一步，检索器找出看起来相关的段落。第二步，模型读这些段落并写出答案。",
    ),
    # Leading and trailing whitespace, and runs of blank lines.
    (
        "padded",
        "\n\n  A first paragraph, indented.  \n\n\n\n  A second paragraph.  \n\n",
    ),
    # Text shorter than any chunk size.
    ("short", "one line"),
    # A single word longer than a chunk, surrounded by normal words.
    ("long-word", "before supercalifragilisticexpialidocious after"),
]

CONFIGS = [
    (20, 5, "start", True),
    (20, 5, "end", True),
    (20, 5, "drop", True),
    (40, 10, "start", True),
    (40, 10, "start", False),
    (64, 0, "start", True),
    (1000, 200, "start", True),
]

SEPARATORS = ["\n\n", "\n", " ", ""]

TOKEN_CONFIGS = [
    (8, 2),
    (8, 0),
    (16, 4),
    (32, 8),
]


def word_count(text: str) -> int:
    """The token counter the token-splitter cases are measured with: space-delimited words."""
    return len([piece for piece in text.split(" ") if piece])


def moonbit_string(value: str) -> str:
    out = ['"']
    for char in value:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\t":
            out.append("\\t")
        elif char == "\r":
            out.append("\\r")
        elif 0x20 <= ord(char) < 0x7F:
            out.append(char)
        else:
            out.append("\\u{%X}" % ord(char))
    out.append('"')
    return "".join(out)


def token_cases() -> list:
    from langchain_text_splitters import CharacterTextSplitter

    cases = []
    for name, text in CORPUS:
        for chunk_size, chunk_overlap in TOKEN_CONFIGS:
            splitter = CharacterTextSplitter(
                separator=" ",
                keep_separator=True,
                length_function=word_count,
                chunk_size=chunk_size,
                chunk_overlap=chunk_overlap,
                strip_whitespace=True,
            )
            cases.append(
                (name, text, chunk_size, chunk_overlap, splitter.split_text(text))
            )
    return cases


def generate() -> str:
    from langchain_text_splitters import RecursiveCharacterTextSplitter

    cases = []
    for name, text in CORPUS:
        for chunk_size, chunk_overlap, keep, strip in CONFIGS:
            keep_value = {"start": True, "end": "end", "drop": False}[keep]
            splitter = RecursiveCharacterTextSplitter(
                separators=SEPARATORS,
                keep_separator=keep_value,
                chunk_size=chunk_size,
                chunk_overlap=chunk_overlap,
                strip_whitespace=strip,
                length_function=len,
            )
            expected = splitter.split_text(text)
            cases.append((name, text, chunk_size, chunk_overlap, keep, strip, expected))

    lines = [
        "// Generated by scripts/gen_split_vectors.py from langchain-text-splitters",
        f"// {EXPECTED}. Do not edit: change the script and regenerate.",
        "",
        "///|",
        "/// One splitter case: what went in, how it was configured, what came out.",
        "pub(all) struct SplitCase {",
        "  name : String",
        "  text : String",
        "  separators : Array[String]",
        "  chunk_size : Int32",
        "  chunk_overlap : Int32",
        "  keep : String",
        "  strip_whitespace : Bool",
        "  expected : Array[String]",
        "}",
        "",
        "///|",
        f"/// The {len(cases)} cases, replayed by the splitter conformance test.",
        "pub fn split_cases() -> Array[SplitCase] {",
        "  [",
    ]
    separators = "[" + ", ".join(moonbit_string(s) for s in SEPARATORS) + "]"
    for name, text, chunk_size, chunk_overlap, keep, strip, expected in cases:
        chunks = ", ".join(moonbit_string(chunk) for chunk in expected)
        lines.append(
            "    { name: %s, text: %s, separators: %s, chunk_size: %d, "
            "chunk_overlap: %d, keep: %s, strip_whitespace: %s, expected: [%s] },"
            % (
                moonbit_string(name),
                moonbit_string(text),
                separators,
                chunk_size,
                chunk_overlap,
                moonbit_string(keep),
                "true" if strip else "false",
                chunks,
            )
        )
    lines.append("  ]")
    lines.append("}")
    lines.append("")
    lines.append("///|")
    lines.append("/// One token-splitter case, measured in space-delimited words.")
    lines.append("pub(all) struct TokenCase {")
    lines.append("  name : String")
    lines.append("  text : String")
    lines.append("  chunk_size : Int32")
    lines.append("  chunk_overlap : Int32")
    lines.append("  expected : Array[String]")
    lines.append("}")
    lines.append("")
    tokens = token_cases()
    lines.append("///|")
    lines.append(f"/// The {len(tokens)} token cases, replayed by the token splitter conformance test.")
    lines.append("pub fn token_cases() -> Array[TokenCase] {")
    lines.append("  [")
    for name, text, chunk_size, chunk_overlap, expected in tokens:
        chunks = ", ".join(moonbit_string(chunk) for chunk in expected)
        lines.append(
            "    { name: %s, text: %s, chunk_size: %d, chunk_overlap: %d, expected: [%s] },"
            % (
                moonbit_string(name),
                moonbit_string(text),
                chunk_size,
                chunk_overlap,
                chunks,
            )
        )
    lines.append("  ]")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    import importlib.metadata

    installed = importlib.metadata.version("langchain-text-splitters")
    if installed != EXPECTED:
        print(
            f"warning: generating from langchain-text-splitters {installed}, "
            f"the fixtures were written for {EXPECTED}",
            file=sys.stderr,
        )
    sys.stdout.write(generate())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
